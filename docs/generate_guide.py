def TBL(story, headers, rows, ratios, caption_text=None, header_bg=HEADER_FILL,
        center_cols=()):
    widths = [r * AVAIL for r in ratios]
    data = [[Paragraph("<b>%s</b>" % htxt, th) for htxt in headers]]
    for row in rows:
        cells = []
        for ci, cell in enumerate(row):
            cells.append(Paragraph(cell, tdc if ci in center_cols else td))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), header_bg),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
             ("LEFTPADDING", (0, 0), (-1, -1), 6),
             ("RIGHTPADDING", (0, 0), (-1, -1), 6),
             ("TOPPADDING", (0, 0), (-1, -1), 4.5),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5)]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(("BACKGROUND", (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    story.append(t)
    if caption_text:
        story.append(Spacer(1, 5))
        story.append(Paragraph(caption_text, caption))
    story.append(Spacer(1, 12))



def box(d, x, y, w, h, title, sub=None, fill=BOX_FILL, edge=ICON):
    d.add(Rect(x, y, w, h, rx=4, ry=4, fillColor=fill, strokeColor=edge, strokeWidth=1.1))
    ty = y + h / 2 + (3.2 if sub else -3.2)
    d.add(String(x + w / 2, ty, title, fontName="TNR-Bold", fontSize=8.6,
                 fillColor=TEXT_PRIMARY, textAnchor="middle"))
    if sub:
        d.add(String(x + w / 2, y + h / 2 - 9.5, sub, fontName="TNR", fontSize=7,
                     fillColor=TEXT_MUTED, textAnchor="middle"))


def arrow(d, pts, label=None, lpos=None, lsize=6.6, color=COVER_BLOCK):
    for i in range(len(pts) - 2):
        x1, y1 = pts[i]; x2, y2 = pts[i + 1]
        d.add(Line(x1, y1, x2, y2, strokeColor=color, strokeWidth=1.0))
    x1, y1 = pts[-2]; x2, y2 = pts[-1]
    d.add(Line(x1, y1, x2, y2, strokeColor=color, strokeWidth=1.0))
    import math
    ang = math.atan2(y2 - y1, x2 - x1)
    L, Wd = 6.0, 3.2
    p1 = (x2 - L * math.cos(ang) + Wd * math.sin(ang), y2 - L * math.sin(ang) - Wd * math.cos(ang))
    p2 = (x2 - L * math.cos(ang) - Wd * math.sin(ang), y2 - L * math.sin(ang) + Wd * math.cos(ang))
    d.add(Polygon(points=[p1[0], p1[1], p2[0], p2[1], x2, y2], fillColor=color, strokeColor=None))
    if label:
        lx, ly = lpos if lpos else ((x1 + x2) / 2, (y1 + y2) / 2 + 3)
        d.add(String(lx, ly, label, fontName="TNR-Italic", fontSize=lsize,
                     fillColor=TEXT_MUTED, textAnchor="middle"))



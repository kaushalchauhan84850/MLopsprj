H1(story, "5.  Prometheus - The Metrics Brain")
H2(story, "5.1  What it is")
P(story, "Prometheus is a time-series database plus a scraper plus a query language. Every few seconds "
         "it <b>pulls</b> an HTTP endpoint (<b>/metrics</b>) on each target and stores the numeric "
         "samples with their label sets. It also evaluates <b>PromQL</b> expressions - the language "
         "used everywhere in this project, from Grafana panels to the collector's feature queries to "
         "KEDA's scaling triggers.")
H2(story, "5.2  How the pull model works, and why it beats push")
P(story, "In pull-based monitoring the server initiates: Prometheus discovers targets (from Kubernetes "
         "API service discovery), fetches each target every scrape interval, and records success. A "
         "failed scrape produces the synthetic metric <b>up == 0</b> - so \"is the target alive\" is "
         "itself a queryable time series. In a push world a crashed exporter leaves the server holding "
         "a stale last value that looks healthy; in a pull world the absence of a successful scrape is "
         "loud and immediate. Pull also means the monitoring server decides the cadence and can be "
         "re-scraped at higher rate while debugging - no client reconfiguration.")
H2(story, "5.3  PromQL - the one language every later stage speaks")
